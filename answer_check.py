# (b) repetition loops
# --------------------------------------------------------------------------- #
_LINE_MIN_LEN = 12
# A loop only counts when it runs to the END of the answer (a runaway loops
# until the cap): 3 copies there if the reply hit the token cap, 5 otherwise
# (a song may legitimately end on a line sung three times). Mid-text repeats
# -- four identical `<span class="star">` lines in an HTML page, a chorus --
# are content, and need _MID_MIN_RUN copies before they count.
_LINE_MIN_RUN = 3
_END_MIN_RUN = 5
_MID_MIN_RUN = 8
# finish_reason for text of a stream still in progress: its current end is not
# the answer's end (every mid-text repeat is briefly "at the end"), so a loop
# reaching it needs the MID-text copy count.
PARTIAL = "__partial__"
# A looping unit is 8..160 chars: shorter is "ha ha ha" / "0x00, 0x00" land,
# longer is a paragraph (caught per line by _line_loop).
_UNIT_MIN = 8
_UNIT_MAX = 160
_PRECHECK_IGNORE = frozenset(" \t\r\n|")


def _unit_is_meaningful(unit):
    stripped = unit.strip()
    if not stripped or stripped.startswith("|"):
        return False            # markdown table rows legitimately repeat
    distinct = {c for c in stripped if not c.isspace()}
    letters = sum(1 for c in stripped if c.isalpha())
    return len(distinct) >= 5 and letters >= 3


def _line_is_meaningful(norm):
    # short lines ("---", "}", "Yes.") and table rows repeat legitimately
    return (len(norm) >= _LINE_MIN_LEN and not norm.startswith("|")
            and any(c.isalnum() for c in norm))


def _end_min_run(finish_reason):
    if finish_reason == PARTIAL:
        return _MID_MIN_RUN
    return _LINE_MIN_RUN if finish_reason == "length" else _END_MIN_RUN


# STRUCTURED LINES repeat legitimately: list items ("- TBD by the owner",
# "- [ ] Review the migration"), table rows without a leading pipe, test
# runner / log output ("test_x ... ok", "[WARN] retrying connection",
# "PASSED", "12:00:01 GET /health 200"), indented code/output, key: value
# records, REPL/shell lines. A runaway loop never stops by itself -- it runs to
# the token cap -- so for these lines:
#   * finish "length": the plain rule (3 copies at the end: the cap IS the loop);
#   * a natural finish: a run is content up to _STRUCT_END_MAX_RUN copies (the
#     model chose to stop there);
#   * a stream still going: _STRUCT_PARTIAL_MIN_RUN copies must reach the end;
#   * mid-text (more content follows): _STRUCT_PARTIAL_MIN_RUN copies, not 8.
_STRUCT_PARTIAL_MIN_RUN = 16
_STRUCT_END_MAX_RUN = 50
_STRUCT_LINE_RE = re.compile(
    r"""^(?:
        (?:\ {4}|\t)                                   # indented code / output
      | \s*(?:[-*+•]|\d{1,4}[.)]|[A-Za-z][.)])\s  # bullet / numbered item
      | \s*\[[^\]\n]{1,40}\]                           # [INFO] / [PASS] / [ ]
      | \s*\d{4}-\d{2}-\d{2}                           # dated log line
      | \s*\d{1,2}:\d{2}(?::\d{2})?\b                  # timed log line
      | \s*(?:PASS(?:ED)?|FAIL(?:ED)?|ok|not\ ok|OK|ERROR|WARN(?:ING)?|INFO
              |DEBUG|TRACE|SKIP(?:PED)?|XFAIL|XPASS)(?=[\s:\]]|$)  # test / log
      | \s*[✓✔✗✘×√]      # check / cross marks
      | \s*(?:>>>|\.\.\.|\$|PS\ [A-Z]:\\[^>]*>)\s      # REPL / shell prompt
      | \s*[A-Za-z_][\w.-]{0,30}(?:\ [A-Z][\w.-]*)?:\s+\S  # key: value record
    )""", re.X)
_STRUCT_END_RE = re.compile(r"(?:\.\.\.\s*(?:ok|OK|PASSED|FAILED|passed|failed|done)"
                            r"|\s(?:PASSED|FAILED|SKIPPED|ok|OK))\s*$")


def _line_is_structured(line):
    """A list item, table row, test/log output line, indented code or a
    key: value record -- shapes that repeat verbatim in real answers."""
    if not line or not line.strip():
        return False
    if line.count("|") >= 2 or "\t" in line.strip():
        return True             # a table row, with or without a leading pipe
    if "::" in line and re.search(r"\w::\w", line):
        return True             # pytest node ids / C++ scopes
    return bool(_STRUCT_LINE_RE.match(line) or _STRUCT_END_RE.search(line))


def _struct_end_allows(run, finish_reason):
    """True when a run of `run` structured lines reaching the text's end is
    content under `finish_reason` (see _STRUCT_LINE_RE's comment)."""
    if finish_reason == "length":
        return run < _LINE_MIN_RUN
    if finish_reason == PARTIAL:
        return run < _STRUCT_PARTIAL_MIN_RUN
    return run < _STRUCT_END_MAX_RUN


def _line_loop(masked, prompt_text, finish_reason=None):
    """Offset just past the first copy of a line repeated in a row: at least
    _MID_MIN_RUN copies anywhere, or _end_min_run copies running to the end.
    Structured lines (_line_is_structured) follow their own rule."""
    prev = None
    prev_raw = ""
    run = 0
    first_end = 0
    pos = 0

    def hit(norm):
        if not _line_is_meaningful(norm):
            return None
        if prompt_text and (norm + "\n" + norm) in prompt_text:
            return None
        return first_end

    for line in masked.split("\n"):
        start = pos
        pos += len(line) + 1
        norm = line.strip()
        if not norm:
            continue            # blank lines between copies do not break a run
        if _PUA_RE.search(norm):
            prev, run = None, 0     # a fenced code block breaks any run
            continue
        if norm == prev:
            run += 1
            if run >= (_STRUCT_PARTIAL_MIN_RUN if _line_is_structured(prev_raw)
                       else _MID_MIN_RUN):
                cut = hit(norm)
                if cut is not None:
                    return cut
        elif prev is not None and prev.startswith(norm) and not masked[pos:].strip():
            pass                # partial last copy of a loop cut by the cap
        else:
            prev = norm
            prev_raw = line
            run = 1
            first_end = start + len(line)
    if prev is not None and run >= _end_min_run(finish_reason):
        if _line_is_structured(prev_raw) and _struct_end_allows(run, finish_reason):
            return None
        return hit(prev)
    return None


def _loop_lines_structured(region):
    """True when every whole line of a loop region (its first line may be a
    partial copy, so it is skipped; so is a last line still being written)
    is a structured line."""
    lines = [ln for ln in region.split("\n")[1:] if ln.strip()]
    if len(lines) > 1 and any(o != lines[-1] and o.startswith(lines[-1])
                              for o in lines[:-1]):
        lines.pop()
    return bool(lines) and all(_line_is_structured(ln) for ln in lines)


def _tail_loop(masked, prompt_text, finish_reason=None):
    """Offset just past the FIRST copy of a unit that repeats, back to back and
    at least 3 times, up to the very END of the answer.

    End-anchored on purpose: a degenerate generation loops until the token cap,
    so the loop IS the tail. That turns the search into ~150 C-speed slice
    compares (one per candidate period) instead of a backtracking regex over
    the whole text -- MEASURED: `(.{8,160}?)\\1{2,}` cost ~40 ms on 4 KB of
    plain prose, twenty times the budget. Mid-text line loops are
    _line_loop's job."""
    s = masked.rstrip()
    n = len(s)
    for p in range(_UNIT_MIN, _UNIT_MAX + 1):
        if 3 * p > n:
            break
        # s[i] == s[i+p] across the last 3p chars <=> 3 copies of period p
        if s[n - 3 * p:n - p] != s[n - 2 * p:n]:
            continue
        chars = set(s[n - p:n]) - _PRECHECK_IGNORE
        if len(chars) < 5:
            continue            # rotation-invariant, C-speed: skip "aaaa…" walks
        start = n - 3 * p
        while start - p >= 0 and s[start - p:start] == s[start:start + p]:
            start -= p          # whole earlier copies
        while start > 0 and s[start - 1] == s[start - 1 + p]:
            start -= 1          # ...and the partial one the loop began with
        unit = s[start:start + p]
        if not _unit_is_meaningful(unit):
            continue
        copies = (n - start) // p
        if copies < _end_min_run(finish_reason):
            continue            # 3-4 copies at the end of a finished reply: content
        if "\n" in unit and _loop_lines_structured(s[start:]) \
                and _struct_end_allows(copies, finish_reason):
            continue            # whole list items / rows / log lines, repeated
        if prompt_text and unit * 2 in prompt_text:
            continue            # the user asked for this repetition
        return start + p
    return None


# GLUED short-unit loops: "2826HAMSTER-2826282628262826282628262826". The unit
# is below _tail_loop's 8-char floor and has too few distinct chars for it, and
# there is no whitespace, so _line_loop never sees a line. Same end-anchored
# rule as _tail_loop (a runaway loops until the cap), plus:
#   * 4+ copies at the token cap; 8+ at a natural stop, and then only for a
#     unit carrying a DIGIT -- "hahahahaha" or a CAG repeat ending a finished
#     reply is content;
#   * no whitespace in the unit (spaced repeats are _tail_loop's) and at least
#     two distinct chars one of them alnum ("aaaa" / "=-=-" are not loops here);
#   * a repeating decimal or radix literal ("0.090909…", "0b1010…") is a number;
#   * the prompt asked for it (the unit doubled, or the unit plus "repeat").
_GLUE_MIN, _GLUE_MAX = 2, 16
_GLUE_MIN_RUN_CAP = 4
_GLUE_MIN_RUN = 8
# ...and 32 on a stream still going: "1010101010101010" (8 copies) mid-sentence
# is a number the next delta continues past.
_GLUE_MIN_RUN_PARTIAL = 32
_NUMBER_PREFIX_RE = re.compile(r"(?:\d[.,]|0[xXbBoO])$")
_REPEAT_ASK_RE = re.compile(r"repeat|times|répét|fois", re.I)


def _periodic_start(s, p):
    """Smallest i with s[i:] periodic in p (s already known periodic over its
    last 4p chars). Monotone, so a binary search of C-speed slice compares --
    a 20 KB loop costs ~15 compares, not 10k stride steps."""
    n = len(s)
    lo, hi = 0, n - 4 * p
    while lo < hi:
        mid = (lo + hi) // 2
        if s[mid:n - p] == s[mid + p:n]:
            hi = mid
        else:
            lo = mid + 1
    return lo


def _glued_loop(masked, prompt_text, finish_reason):
    s = masked.rstrip()
    n = len(s)
    capped = finish_reason == "length"
    need = _GLUE_MIN_RUN_CAP if capped else (
        _GLUE_MIN_RUN_PARTIAL if finish_reason == PARTIAL else _GLUE_MIN_RUN)
    for p in range(_GLUE_MIN, _GLUE_MAX + 1):
        if 4 * p > n:
            break
        if s[n - 4 * p:n - p] != s[n - 3 * p:n]:
            continue
        tail = s[n - p:n]
        if any(c.isspace() for c in tail) or len(set(tail)) < 2:
            continue
        if not any(c.isalnum() for c in tail) or _PUA_RE.search(tail):
            continue
        start = _periodic_start(s, p)
        unit = s[start:start + p]
        if (n - start) // p < need:
            continue
        if not capped and not any(c.isdigit() for c in unit):
            continue
        head = s[:start]
        if _NUMBER_PREFIX_RE.search(head):
            continue
        if prompt_text and (unit * 2 in prompt_text
                            or (unit in prompt_text and _REPEAT_ASK_RE.search(prompt_text))):
            continue
        core = head.strip()
        if not core:
            return start + p    # the loop IS the reply: keep its first copy
        if core.startswith(unit) and not re.search(r"\s", core):
            # "2826HAMSTER-" + loop: one glued token that opens with the unit --
            # the answer, junk, then the answer again. Keep the answer.
            return (len(head) - len(head.lstrip())) + p
        return start
    return None


# SEPARATOR RUNS: "1573 1573 ------------------------------". 8+ identical
# punctuation chars running to the END, on the same line as answer text.
# A markdown rule / setext underline / fence sits on its own line and a table
# row carries "|", so neither ever qualifies. Fires at the token cap, or at any
# finish when the answer before it is itself one token repeated ("1573 1573").
_SEP_TAIL_RE = re.compile(r"([^\w\s])\1{7,}$")


def _repeated_token_end(line):
    """End offset (within `line`) of the first token when the line is one
    token repeated 2+ times ("1573 1573 "), else None."""
    toks = line.split()
    if len(toks) < 2 or any(t != toks[0] for t in toks):
        return None
    return line.index(toks[0]) + len(toks[0])


def _separator_run(masked, finish_reason):
    s = masked.rstrip()
    m = _SEP_TAIL_RE.search(s)
    if not m or _PUA_RE.match(m.group(1)):
        return None
    start = m.start()
    line_start = s.rfind("\n", 0, start) + 1
    head_line = s[line_start:start]
    if not re.search(r"\w", head_line) or "|" in head_line:
        return None
    if head_line.lstrip().startswith(m.group(1) * 3):
        return None             # a banner: "===== 5 passed in 0.12s ====="
    first = _repeated_token_end(head_line)
    if first is not None:
        return line_start + first
    if finish_reason == "length":
        return start
    return None


# LEAKED REASONING / TEMPLATE MARKERS after an answer. A reply that OPENS with
# a <think> block is how some providers ship reasoning and is left alone; only
# a marker at an odd place counts: <think> or a template token after answer
# text, "Thinking content:" after answer text, "Thought:" glued mid-line after
# a number/sentence end (not "Food for Thought:", not a ReAct line start), and
# a stray </think> with no opener that closes a SHORT head (a long head before
# it is the scratchpad itself, and its answer is after the tag -- not ours).
_THINK_OPEN_RE = re.compile(r"<think(?:ing)?>", re.I)
_THINK_CLOSE_RE = re.compile(r"</think(?:ing)?>", re.I)
_THINK_BLOCK_RE = re.compile(r"<(think|thinking)>.*?</\1>", re.I | re.S)
_THINK_LABEL_RE = re.compile(r"Thinking content\s*:", re.I)
_THOUGHT_RE = re.compile(r"\bThought:")
_TEMPLATE_TOKEN_RE = re.compile(
    r"<\|(?:im_start|im_end|endoftext|end_of_text|eot_id|eom_id|start_header_id|"
    r"end_header_id|end_of_turn|start_of_turn)\|>|<(?:end_of_turn|start_of_turn)>")
_REASON_PROMPT_RE = re.compile(r"think>|thinking content|thought:|<\||_of_turn>", re.I)
_SHORT_STRAY_HEAD = 40


def _has_answer_before(masked, pos):
    return re.search(r"\w", _THINK_BLOCK_RE.sub("", masked[:pos])) is not None


def _reasoning_leak(masked, prompt_text):
    if prompt_text and _REASON_PROMPT_RE.search(prompt_text):
        return None             # the user is asking ABOUT these markers
    hits = []
    for rx in (_THINK_OPEN_RE, _THINK_LABEL_RE, _TEMPLATE_TOKEN_RE):
        for m in rx.finditer(masked):
            if _has_answer_before(masked, m.start()):
                hits.append(m.start())
                break
    for m in _THINK_CLOSE_RE.finditer(masked):
        head = masked[:m.start()]
        if _THINK_OPEN_RE.search(head):
            continue            # a well-formed block
        core = head.strip()
        if core and len(core) <= _SHORT_STRAY_HEAD and re.search(r"\w", core):
            hits.append(m.start())
        break
    for m in _THOUGHT_RE.finditer(masked):
        before = masked[masked.rfind("\n", 0, m.start()) + 1:m.start()].rstrip()
        if before and not before[-1].isalpha() and re.search(r"\w", before):
            hits.append(m.start())
            break
    return min(hits) if hits else None


# --------------------------------------------------------------------------- #
# (d) prompt-constrained brevity: "Answer with only the number." + "8446\"Sfc
# cover\" is an additional paramet" -- a correct answer, then a same-script
# runaway no other check can call junk. When the LAST user turn explicitly
# asks for exactly one short thing, the leading short answer IS the reply.
# Guards (a false positive here trims a real answer):
#   * the ask must be imperative ("Answer with only the number", "Number
#     only.", "in one word", "reply with exactly PONG") -- "is 2 the only
#     number that..." is a question, not a format;
#   * a prompt that also asks for an explanation/steps/"then ..." is skipped,
#     and so is a long prompt (a pasted task that merely contains the phrase);
#   * never with tools (agent turns), never on a reply that opens with markup;
#   * a number must end where the number ends: "2 + 2 = 4", "10:30", "0xFF",
#     "6.02e23", "3rd", "1 573" are never cut, and a leading number the prompt
#     itself contains, followed by more digits, is an echo of the question
#     ("2825 plus 1 is 2826"), not the answer;
#   * a Capitalised word followed by another ("New York") is a name, not a word.
# --------------------------------------------------------------------------- #
_BRIEF_PROMPT_MAX = 1200
_BRIEF_KIND = (r"(?P<kind>yes or no|yes/no|oui ou non|numbers?|numerals?|digits?|integers?|"
               r"figures?|nombres?|chiffres?|words?|mots?|letters?|lettres?)")
_BRIEF_ARTS = r"(?:(?:with|by|par|avec|the|a|an|one|1|single|le|la|un|une|seul|seule)\s+)*"
_BRIEF_RES = (
    # "answer with only the number", "just the word", "uniquement par le nombre"
    (re.compile(r"\b(?:only|just|solely|exactly|nothing but|uniquement|seulement|juste)\s+"
                + _BRIEF_ARTS + _BRIEF_KIND + r"\b", re.I), True),
    # "reply with just the answer"
    (re.compile(r"\b(?:only|just)\s+(?:give\s+|return\s+|output\s+)?the\s+(?:final\s+)?"
                r"(?P<kind>answer|result|value|sum|total)\b", re.I), True),
    # "Number only."
    (re.compile(r"\b" + _BRIEF_KIND + r"\s+(?:only|uniquement|seulement)\b", re.I), True),
    # "in one word", "with a single word", "one-word answer"
    (re.compile(r"\b(?:in|with|using)\s+(?:(?:a|one|1|single)\s+)+(?P<kind>word)\b"
                r"|\b(?:one|single)[- ](?P<kind2>word)\s+(?:answer|reply|response|only)\b"
                r"|\b(?:en un|un seul)\s+(?P<kind3>mot)\b", re.I), False),
)
_BRIEF_VERB_RE = re.compile(
    r"\b(?:answer|reply|respond|give|return|output|print|say|write|provide|state|type|"
    r"r[ée]ponds|r[ée]pondez|donne|donnez|[ée]cris|[ée]crivez)", re.I)
_BRIEF_LITERAL_RE = re.compile(
    r"\b(?:reply|respond|answer|say|output|return)\s+(?:with\s+)?exactly\s*:?\s*"
    r"(?:[\"'“‘`](?P<q>[^\"'”’`\n]{1,40})[\"'”’`]|(?P<w>[A-Za-z0-9_-]{1,40})\b)", re.I)
_BRIEF_NOT_LITERAL = frozenset(("one", "a", "an", "the", "single", "two", "three", "1", "2", "3"))
_BRIEF_BLOCK_RE = re.compile(
    r"\b(?:explain|explanation|justif\w*|why|reason\w*|show (?:your |the )?work|"
    r"step[- ]by[- ]step|then|followed by|after that|if (?:yes|no|so)|pourquoi|"
    r"expliqu\w*|puis|ensuite)\b", re.I)
_NUM_KINDS = frozenset(("number", "numeral", "digit", "integer", "figure", "nombre",
                        "chiffre", "answer", "result", "value", "sum", "total"))
_WORD_KINDS = frozenset(("word", "mot"))
_LETTER_KINDS = frozenset(("letter", "lettre"))
_YN_KINDS = frozenset(("yes or no", "yes/no", "oui ou non"))
_LEAD_NUM_RE = re.compile(
    r"\s*[-+−]?\$?(?:\d{1,3}(?:[ \xa0 ]\d{3})+(?!\d)|\d+(?:,\d{3})*(?:[.,]\d+)?)%?")
_NUM_CONT_RE = re.compile(
    r"\s*[-+*/×÷=^<>:]|[0-9A-Fa-f]+\b|[eE][+-]?\d|[xXbBoO][0-9A-Fa-f]|(?:st|nd|rd|th)\b")
_LEAD_WORD_RE = re.compile(r"\s*[A-Za-zÀ-ÖØ-öø-ɏ][A-Za-zÀ-ÖØ-öø-ɏ0-9'’]*(?:-[A-Za-zÀ-ÖØ-öø-ɏ0-9]+)*")
_LEAD_YN_RE = re.compile(r"\s*(?:yes|no|oui|non)\b", re.I)
_TRAILING_OK = " \t\r\n.!?。"


def _brief_kinds(prompt):
    """{kind classes} the prompt imperatively constrains the reply to, plus a
    literal token for "reply with exactly X" (or None)."""
    kinds = set()
    for rx, needs_verb in _BRIEF_RES:
        for m in rx.finditer(prompt):
            if needs_verb:
                cut = max(prompt.rfind(c, 0, m.start()) for c in ".?!\n;")
                lead = prompt[cut + 1:m.start()]
                if lead.strip() and not _BRIEF_VERB_RE.search(lead):
                    continue    # "is 2 the only number that...": not a format
            kind = next(g for g in m.groups() if g).lower()
            kind = kind if kind in _YN_KINDS else kind.rstrip("s")
            if kind in _NUM_KINDS:
                kinds.add("num")
            elif kind in _WORD_KINDS:
                kinds.add("word")
            elif kind in _LETTER_KINDS:
                kinds.add("letter")
            elif kind in _YN_KINDS:
                kinds.add("yn")
    literal = None
    m = _BRIEF_LITERAL_RE.search(prompt)
    if m:
        literal = m.group("q") or m.group("w")
        if literal and literal.lower() in _BRIEF_NOT_LITERAL:
            literal = None
    return kinds, literal


_GLUED_NUM_MIN_UNIT = 3          # "121212" / "111" can be real answers
_GLUED_NUM_MIN_COPIES = 3


def _glued_number_period(num):
    """Unit length when an all-digit `num` is one 3+ digit unit glued to
    itself 3+ times (a trailing partial copy allowed: the cap cut it), else
    None. MEASURED LIVE (stream, llm7/GLM-5.3-Flash, "What is 3191 plus 1?
    Answer with only the number.", max_tokens 40): "319231923192". A number
    with a shorter period ("111111", "121212") is left alone -- those are
    plausible real answers, and a false cut here trims one."""
    if not num.isdigit():
        return None
    n = len(num)
    for short in (1, 2):
        if n > short and num == (num[:short] * n)[:n]:
            return None
    for p in range(_GLUED_NUM_MIN_UNIT, n // _GLUED_NUM_MIN_COPIES + 1):
        if num == (num[:p] * (n // p + 1))[:n]:
            return p
    return None


@functools.lru_cache(maxsize=64)
def _brevity(prompt):
    """(frozenset of kinds, literal) the LAST user turn -- its own words, CLI
    wrappers removed -- imperatively constrains the reply to; (frozenset(),
    None) when it does not, or when a guard says it is not a bare-value
    format (a long pasted task, an explanation also asked for)."""
    p = _instruction(prompt) if isinstance(prompt, str) else None
    if not p or len(p) > _BRIEF_PROMPT_MAX or _BRIEF_BLOCK_RE.search(p):
        return frozenset(), None
    kinds, literal = _brief_kinds(p)
    return frozenset(kinds), literal


def brevity_ask(last_prompt):
    """True when the last user turn asks for one bare value ("Reply with only
    the number", "in one word", "reply with exactly PONG"). The stream gate
    then holds the whole short answer and judges it before release. Never
    raises (False)."""
    try:
        kinds, literal = _brevity(last_prompt if isinstance(last_prompt, str) else
                                  (str(last_prompt) if last_prompt else None))
        return bool(kinds or literal)
    except Exception:                                            # noqa: BLE001
        return False


# "2768.2768" / "11991199.1199" for "What is 2767 plus 1? Answer with only the
# number." (REPORTED 2026-09-28): the answer, a dot, and the answer again --
# the same glued-copy degeneration as "319231923192", but with a dot in it the
# whole thing IS a well-formed decimal. Cutting it would trim a reply that
# could be a real value (a price, a version-like figure), so it is never cut:
# it is only FLAGGED ("echoed_decimal", ok stays True) so the caller can file
# a junk quality strike for the (provider, model) that said it. Guards: a
# constrained number ask, no tools, the right side 3+ digits, the left side
# 1+ whole copies of it, and the value not in the prompt.
_ECHOED_DECIMAL_RE = re.compile(r"\s*[-+]?(?P<left>\d+)\.(?P<right>\d{3,})\s*[.!]?\s*")


def echoed_decimal(text, last_prompt, tools_offered=False):
    """True when `text` is a bare number made of one digit run repeated around
    a dot ("2768.2768", "11991199.1199") under a "only the number" ask. A
    QUALITY SIGNAL, never a cut. Never raises (False)."""
    try:
        if tools_offered or not isinstance(text, str) or not last_prompt:
            return False
        kinds, _literal = _brevity(last_prompt if isinstance(last_prompt, str)
                                   else str(last_prompt))
        if "num" not in kinds:
            return False
        m = _ECHOED_DECIMAL_RE.fullmatch(text)
        if not m:
            return False
        left, right = m.group("left"), m.group("right")
        if len(left) % len(right) or left != right * (len(left) // len(right)):
            return False
        value = "%s.%s" % (left, right)
        return value not in (_instruction(last_prompt) or "")
    except Exception:                                            # noqa: BLE001
        return False


def _constrained_extra(text, prompt, tools_offered):
    if tools_offered or not prompt:
        return None
    kinds, literal = _brevity(prompt)
    if not kinds and not literal:
        return None
    prompt = _instruction(prompt)   # the echo checks below: the user's words only
    head = text[:400]
    cut = None
    if literal:
        lead = len(head) - len(head.lstrip())
        if head[lead:lead + len(literal)].lower() == literal.lower():
            end = lead + len(literal)
            if end >= len(head) or not head[end].isalnum():
                cut = end
    if cut is None and "num" in kinds:
        m = _LEAD_NUM_RE.match(head)
        suffix = _GLUE_RUN_RE.match(head, m.end()) if m else None
        if suffix and _suffix_ok(suffix.group(0)):
            m = None            # "5ème", "1º", "10µs": the number's own suffix
        if m and not _NUM_CONT_RE.match(head, m.end()):
            num = m.group(0).strip()
            p = _glued_number_period(num)
            if p and num not in prompt:
                # "319231923192": the answer glued to copies of itself. Every
                # copy is inside ONE numeric token, so the checks above see a
                # single long number that "ends where the number ends".
                cut = m.end() - len(num) + p
            else:
                echo = re.search(r"(?<![\d.,])" + re.escape(num) + r"(?![\d.,]*\d)", prompt)
                if not (echo and re.search(r"\d", head[m.end():])):
                    cut = m.end()
    if cut is None and "yn" in kinds:
        m = _LEAD_YN_RE.match(head)
        if m:
            cut = m.end()
    if cut is None and ("word" in kinds or "letter" in kinds):
        m = _LEAD_WORD_RE.match(head)
        if m:
            word = m.group(0).strip()
            name = word[:1].isupper() and re.match(r"[ \t]+[A-Z]", head[m.end():])
            if ("word" in kinds or len(word) == 1) and not name:
                cut = m.end()
    if cut is None:
        return None
    if not text[cut:].strip(_TRAILING_OK):
        return None             # nothing extra: the reply complied
    return cut


# --------------------------------------------------------------------------- #
# (e) letters of another Unicode block glued straight onto a bare number
# --------------------------------------------------------------------------- #
# "4349âmara=..." for "Reply with only the number.": the number the prompt
# asked for BARE, then -- no space, no punctuation -- a word whose letters
# come from outside Basic Latin. _constrained_extra would call any extra text
# junk, but stands down on tool turns ("4. Done." may be an agent's report);
# this needs the glued shape, so it runs on tool turns too. Guards:
#   * only for a "num" brevity ask (a word ask is left alone: "café",
#     "Zürich" glue accented letters onto ASCII ones legitimately);
#   * the glued run is 3+ letters and not an ordinal / unit / constant
#     ("5ème", "1ère", "1º", "5ᵉ", "10µs", "10kΩ", "2π");
#   * no letter of that block anywhere in the prompt: a French or Spanish
#     conversation is not a switch to "another" block;
#   * the number-shape guards of _constrained_extra ("0xFF", "6.02e23", an
#     echo of the prompt's own number followed by more digits).
_GLUE_RUN_RE = re.compile(r"[^\W\d_]+")
_GLUED_FOREIGN_MIN = 3
_NUM_SUFFIX_OK_RE = re.compile(
    r"st|nd|rd|th|e|er|re|ère|ere|ème|eme|ième|ieme|nde|o|a|os|as|[ºª]|"
    r"[µμ][a-z]{0,3}|[kKmMG]?[ΩΩ]|[ÅÅ]", re.I)


def _suffix_ok(run):
    """True for letters that legitimately follow a number: an ordinal, a
    unit, a superscript ordinal, a one/two-letter math constant."""
    if _NUM_SUFFIX_OK_RE.fullmatch(run):
        return True
    if all(unicodedata.category(c) == "Lm" for c in run):
        return True                     # "5ᵉ", "1ᵉʳ"
    return len(run) <= 2 and all(0x370 <= ord(c) < 0x400 or 0x2100 <= ord(c) < 0x2150
                                 for c in run)      # "2π", "3ℏ"


def _letter_block(ch):
    cp = ord(ch)
    if cp < 0x80:
        return "ascii"
    if cp < 0x250 or 0x1E00 <= cp < 0x1F00:
        return "latin"                  # Latin-1 / Extended-A/B / Additional
    for key, rx in _SCRIPT_ANY.items():
        if rx.match(ch):
            return key
    return cp >> 7


def _glued_foreign(text, last_prompt, prompt_text):
    if not last_prompt:
        return None
    kinds, _literal = _brevity(last_prompt)
    if "num" not in kinds:
        return None
    head = text[:400]
    m = _LEAD_NUM_RE.match(head)
    if not m or _NUM_CONT_RE.match(head, m.end()):
        return None
    run = _GLUE_RUN_RE.match(head, m.end())
    if not run:
        return None
    word = run.group(0)
    blocks = {_letter_block(c) for c in word if ord(c) >= 0x80}
    if not blocks or len(word) < _GLUED_FOREIGN_MIN or _suffix_ok(word):
        return None
    own = _instruction(last_prompt) or ""
    num = m.group(0).strip()
    echo = re.search(r"(?<![\d.,])" + re.escape(num) + r"(?![\d.,]*\d)", own)
    if echo and re.search(r"\d", head[m.end():]):
        return None             # "2825âbc 2826": the question's number echoed
    for ref in (own, _instruction(prompt_text) if prompt_text else ""):
        if any(ord(c) >= 0x80 and c.isalpha() and _letter_block(c) in blocks
               for c in ref or ""):
            return None         # the conversation writes that block itself
    return m.end()


# --------------------------------------------------------------------------- #
# (f) leaked metadata / chat-template markers after a short answer
# --------------------------------------------------------------------------- #
# "4349âmara=METADATA:8;Note: TOKEN count=298121; REF:5": training-data
# metadata and prompt-template scaffolding the model kept generating after
# its answer. None of it is prose a reply means to contain, but each marker
# alone can appear in a real answer (an S3 doc naming METADATA, a Llama 2
# explainer quoting [INST]), so a marker counts only when
#   * a BARE short answer precedes it ("4349", "Answer: 42", "Yes.") -- the
#     reply was done, and the template went on; or
#   * two different metadata kinds (METADATA / TOKEN count / REF:n) cluster,
#     which no answer writes;
# never when the prompt names any of them, never in code, never at the start.
_META_MARKER_RE = re.compile(
    r"(?P<meta>[=;|]\s*METADATA\b|\bMETADATA\s*[:=]\s*\d)"
    r"|(?P<tok>(?i:\btoken[ _]?count)\s*[=:]\s*\d)"
    r"|(?P<ref>\bREF:\s*\d)"
    r"|(?P<tpl><[|｜][\w.:\-▁]{1,40}[|｜]>|\[/?INST\]|<</?SYS>>|</s>"
    r"|<(?:eos|bos|pad|unk)>"
    r"|^[ \t]*#{2,3}[ \t]*(?:Instruction|Input|Response|Human|Assistant|System)[ \t]*:)",
    re.M)
_META_PROMPT_RE = re.compile(
    r"metadata|token[ _]?count|\bref:|<[|｜]|\[/?inst\]|<</?sys>>|</s>|"
    r"<(?:eos|bos|pad|unk)>|#{2,3}\s*(?:instruction|input|response|human|assistant|system)\b",
    re.I)
_META_CLUSTER = frozenset(("meta", "tok", "ref"))
_BARE_HEAD_RE = re.compile(
    r"\s*(?:[A-Za-z]{1,12}:\s*)?(?:[-+−]?\$?\d[\d,.]*%?|[^\W_]{1,20})[.!]?\s*")
# "4349 Note: TOKEN count=": the label introducing the junk goes with it
_LABEL_TAIL_RE = re.compile(r"(?:(?<=\s)|(?<=[;,])|^)[A-Za-z]{1,12}:\s*$")
_META_SEP_TAIL = " \t\r\n=;:|,"


def _glued_run_start(text, end):
    """Start of a junk letter run glued onto a number ending at `end`
    ("4349âmara" -> 4), else `end`. An ordinal/unit/constant stays, and so
    does a 1-2 letter ASCII tail ("42km")."""
    i = end
    while i > 0 and text[i - 1].isalpha():
        i -= 1
    if i == end or i == 0 or not text[i - 1].isdigit():
        return end
    run = text[i:end]
    if _suffix_ok(run) or (len(run) < _GLUED_FOREIGN_MIN and run.isascii()):
        return end
    return i


def _meta_cut(text, pos):
    """Where the clean answer before a marker at `pos` ends: a dangling label
    and separators go, and so does a junk letter run glued onto a number
    ("4349âmara=METADATA" -> "4349")."""
    head = text[:pos]
    m = _LABEL_TAIL_RE.search(head)
    if m:
        head = head[:m.start()]
    return _glued_run_start(text, len(head.rstrip(_META_SEP_TAIL)))


def _meta_leak(masked, text, prompt_text, at_start=True):
    """Offset of leaked metadata/template junk in `text` (indices shared with
    `masked`), or None. `at_start`: `text` is the reply's head, so the
    bare-answer rule may run (a stream window's head is not the reply's)."""
    hits = [m for m in _META_MARKER_RE.finditer(masked)
            if _has_answer_before(masked, m.start())]
    if not hits:
        return None
    ref = _instruction(prompt_text) if prompt_text else ""
    if ref and _META_PROMPT_RE.search(ref):
        return None             # the user is asking ABOUT these markers
    if at_start:
        cut = _meta_cut(text, hits[0].start())
        if cut and _BARE_HEAD_RE.fullmatch(_THINK_BLOCK_RE.sub("", masked[:cut])):
            return cut
    if len({m.lastgroup for m in hits} & _META_CLUSTER) >= 2:
        first = next(m for m in hits if m.lastgroup in _META_CLUSTER)
        return _meta_cut(text, first.start())
    return None


