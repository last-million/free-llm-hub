# Blocks a CLI injects into a USER turn that are not the user speaking:
# Claude Code's <system-reminder>, Codex's <environment_context> and its
# AGENTS.md <INSTRUCTIONS> / <user_instructions>, slash-command echoes.
# Mirrors ctxwin._WRAPPER_BLOCK_RE / _WRAPPER_LINE_RE -- keep the two in sync
# (copied, not imported: this module stays a leaf).
_WRAPPER_BLOCK_RE = re.compile(
    r"<(system-reminder|environment_context|user_instructions|INSTRUCTIONS|"
    r"user-prompt-submit-hook|command-name|command-message|command-args|"
    r"local-command-stdout|local-command-stderr|turn_aborted)>.*?</\1>",
    re.S | re.I)
_WRAPPER_LINE_RE = re.compile(
    r"^\s*#\s*AGENTS\.md instructions for .*$|"
    r"^\s*Caveat: The messages below were generated by the user while running "
    r"local commands.*$", re.M | re.I)


@functools.lru_cache(maxsize=64)
def _instruction(prompt):
    """`prompt` without CLI wrapper blocks: what the USER typed. MEASURED
    (claude 2.1.x): the last user turn is "<system-reminder>...CLAUDE.md,
    skills...</system-reminder>What is N plus 1? Reply with only the number."
    -- read whole, it is over _BRIEF_PROMPT_MAX and full of "then"/"why", so
    the brevity ask inside it was never seen."""
    if not isinstance(prompt, str) or not prompt:
        return prompt
    if "<" not in prompt and "#" not in prompt and "Caveat" not in prompt:
        return prompt
    out = _WRAPPER_BLOCK_RE.sub("\n", prompt)
    out = _WRAPPER_LINE_RE.sub("", out)
    return out.strip()

# Anything longer is judged on its head (script switch) and tail (loops and
# leaks live at the END of a runaway generation); keeps the check O(cap).
_MAX_SCAN = 24000
_RATIO_WINDOW = 1200            # script-share is judged on this much of the rest

_FENCE_RE = re.compile(r"```.*?(?:```|\Z)", re.S)
_INLINE_CODE_RE = re.compile(r"`[^`\n]{1,300}`")


def _blank(m):
    # per LINE, not per char: a 20 KB code block is ~700 lines, not 20k subs
    return "\n".join(" " * len(part) for part in m.group(0).split("\n"))


def _mask_code(text, partial=False):
    """Same-length copy of `text` with code blanked to spaces (newlines kept),
    so every index found on the mask is valid on the original.

    `partial`: the text is a stream still in progress, so an inline span whose
    closing backtick has not arrived yet ("wrapped in `<think") is code too --
    the fence rule's end-of-text fallback, for inline code."""
    if "`" not in text:
        return text
    out = _INLINE_CODE_RE.sub(_blank, _FENCE_RE.sub(_blank, text))
    if partial:
        i = out.find("`", out.rfind("\n") + 1)
        if i != -1 and len(out) - i <= 300:
            out = out[:i] + " " * (len(out) - i)
    return out


# Loop checks need a DIFFERENT mask: blanking made "- `app.py` updated" and
# "- `cli.py` updated" identical, and turned fenced blocks into skipped blank
# lines, so prose after each of three code blocks read as three copies. Inline
# code stays verbatim here; each fenced block becomes a same-length run of its
# OWN private-use char, which breaks a line run and never equals another block.
_PUA_BASE = 0xE000
_PUA_SPAN = 0x1800
_PUA_RE = re.compile("[-]")


def _mask_fences_distinct(text):
    if "`" not in text:
        return text
    counter = [0]

    def sub(m):
        ch = chr(_PUA_BASE + counter[0] % _PUA_SPAN)
        counter[0] += 1
        return "\n".join(ch * len(part) for part in m.group(0).split("\n"))
    return _FENCE_RE.sub(sub, text)


