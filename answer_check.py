"""Answer-quality gate: is a 200's text a real answer, or an answer with junk
glued on (or only junk)?

MEASURED LIVE (llm7/GLM-5.3-Flash): the model answered correctly, then kept
generating until max_tokens, and the hub served the whole thing as a success:

    "OK出具证明的，原试题解析 做题如有雷同，纯属巧合…"           (prompt had no CJK)
    "6510</arg_value></tool_call>6510</arg_value></tool_call>The user asked"

Every existing check (empty 200, relay error page, refusal, typed tool call)
looked for a BAD answer; none looked for a GOOD answer followed by garbage, so
both counted as clean deliveries and kept that model winning hop 1.

A second live batch (same model, "What is N plus 1? Answer with only the
number.", max_tokens 40) slipped past those first detectors:

    "2826HAMSTER-2826282628262826282628262826"   -> _glued_loop
    "1573 1573 ------------------------------"   -> _separator_run
    "5499 картинка внутри Thinking content: 5"   -> _script_switch (short head)
                                                    + _reasoning_leak
    '8446"Sfc cover" is an additional paramet'   -> _constrained_extra

Leaf module on purpose (no app imports): pure text in, verdict out, trivially
testable and cheap enough to run on every non-streamed answer and once at the
end of every stream.

CONSERVATIVE by design. A false positive either trims a real answer (salvage)
or costs a hop, so every detector demands a strong, specific signal:
  * code (fenced blocks, inline `spans`) is masked out before the script and
    markup checks; the loop checks see inline code verbatim and each fenced
    block as a distinct run-breaker (see _mask_fences_distinct);
  * a repetition loop must run to the END of the answer (or repeat
    _MID_MIN_RUN times mid-text): repeated lines inside raw HTML/CSS/CSV or
    a chorus are content, not a runaway;
  * the script-switch check only fires when the PROMPT never used that script
    and never names its language / asks for a translation, AND the switch is
    either glued straight onto the answer ("OK出具…") or the reply ran to the
    token cap -- a list of greetings after "Here are some:" is neither;
  * markup leaks are only judged when no tools were offered (with tools, the
    typed-tool-call / tool_rescue path owns that shape) and the prompt itself
    does not mention the tag; reasoning markers only at an odd place (a reply
    that OPENS with a <think> block is left alone);
  * the brevity trim needs an IMPERATIVE constraint in the LAST user turn and
    a leading answer that ends cleanly (see _constrained_extra's guards);
  * truncation alone (finish_reason "length") is reported but never fails an
    answer: a plain truncation is common and legitimate (see
    app._chat_json_starved's notes).

A third live sample (2026-09-27, Claude Code over /v1/messages, streamed,
model "max", "What is N plus 1? Reply with only the number.") slipped past
all of the above:

    "4349âmara=METADATA:8;Note: TOKEN count=298121; REF:5"
                                                  -> _glued_foreign
                                                     + _meta_leak

Claude Code offers tools (so the brevity trim stood down) and wraps its
question in <system-reminder> blocks (so the "last user turn" was a long
pasted-looking text); "â" is Latin-1, so no script switch either. Brevity is
now read from the user's own words (_instruction), and the two new detectors
work on tool turns too because they need a junk SHAPE, not just "more text".
"""
