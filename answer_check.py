# (c) leaked tool-call markup in a plain-chat answer
# --------------------------------------------------------------------------- #
_LEAK_RE = re.compile(r"</?tool_call\b[^>]{0,40}>|</?arg_(?:key|value)>", re.I)
_LEAK_PROMPT_RE = re.compile(r"tool_call|arg_value|arg_key", re.I)


def _markup_leak(masked, prompt_text, tools_offered):
    if tools_offered:
        return None             # typed-tool-call / tool_rescue own this shape
    if prompt_text and _LEAK_PROMPT_RE.search(prompt_text):
        return None             # the user is asking ABOUT this markup
    m = _LEAK_RE.search(masked)
    return m.start() if m else None


# A salvage must never turn one number into ANOTHER. The periodic scan in
# _glued_loop walks back over every char that fits the loop, so "2826" followed
# by a "26" loop ("282626262626...") starts the loop at index 2 and would serve
# "28" -- a different number, stated with full confidence. So a cut that lands
# INSIDE a digit run is only kept when everything after it in that run is
# copies of the kept number ("2826" + "28262826..."): that is the first copy of
# the loop, not a prefix of a longer number. Otherwise: no salvage (next hop).
_TRAIL_DIGITS_RE = re.compile(r"\d+$")
_LEAD_DIGITS_RE = re.compile(r"\d+")


def _splits_a_number(text, clean):
    after = text[len(clean):len(clean) + 1]
    if not after.isdigit():
        return False
    if clean[-1:] in ".," and clean[-2:-1].isdigit():
        return True                    # "3." + "14159": a decimal split
    lead = _TRAIL_DIGITS_RE.search(clean)
    if not lead:
        return False
    unit = lead.group(0)
    run = _LEAD_DIGITS_RE.match(text, len(clean)).group(0)
    return run != (unit * (len(run) // len(unit) + 1))[:len(run)]


# A reply that is NOTHING but chat-template tokens and punctuation. MEASURED
# live 2026-09-27 on a codex `exec resume` turn: nvidia/kimi-k3 streamed
# "<|close|>!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!" and it shipped as the answer --
# the head has "close" in it, so the separator-run check saw answer text, and
# "<|close|>" is not one of the known template tokens. No word outside a
# <|...|> token = no answer: cut at 0, no salvage, the chain moves on.
_ANY_SPECIAL_TOKEN_RE = re.compile(r"<[|｜][\w.:\-▁]{1,40}[|｜]>")
# one stray word glued to the token, then only a punctuation run to the end
_TOKEN_WORD_RUN_RE = re.compile(r"^\s*\w{1,16}\s*([^\w\s])\1{7,}\s*$")


def _special_token_junk(text, prompt_text):
    if prompt_text and ("<|" in prompt_text or "<｜" in prompt_text):
        return None             # the user is asking ABOUT these tokens
    if not _ANY_SPECIAL_TOKEN_RE.search(text):
        return None
    rest = _ANY_SPECIAL_TOKEN_RE.sub(" ", text)
    if _TOKEN_WORD_RUN_RE.match(rest):
        return 0                # "<|close|>think!!!!!!!!" (same turn, next try)
    if re.search(r"\w", rest):
        return None
    # A stream head that so far holds only "<|x|>" may still turn into an
    # answer; junk is the token PLUS a run of punctuation after it.
    return 0 if len(re.sub(r"\s", "", rest)) >= 8 else None


def _clip(text):
    if len(text) <= _MAX_SCAN:
        return text
    return text[-_MAX_SCAN:]


# --------------------------------------------------------------------------- #
# A second answer glued onto the first
# --------------------------------------------------------------------------- #
# MEASURED LIVE 2026-09-27 (Claude Code `-p --model max` through the hub): ONE
# upstream stream carried two complete answers back to back, the second glued
# on with no separator at all --
#   "...Nothing else needed. Next: what would you like to do?The last line of
#    big3.txt is: ..."
# -- the model's end-of-turn token was dropped by the provider and sampling
# ran on into a fresh answer. Claude Code prints the last text block, so the
# user saw both. (Verified against the real CLI with a fake server: a SECOND
# block or a second message is never glued in `-p` output; only one block
# holding both answers is.) The signature: the reply's own opening line
# restated right after a non-space character -- a stripped token leaves no
# whitespace, and a real answer does not restate its first sentence glued
# onto its last one.
RESTART_KEY_MAX = 40
_RESTART_KEY_MIN = 18
_RESTART_KEY_WORDS = 3
_RESTART_WORD_RE = re.compile(r"[^\W_]{2,}")
# What may END the first answer right before a glued restatement.
_RESTART_PREV = frozenset('.!?)]}"\'`*’”')
# ...of which these also OPEN a quote / span when a space precedes them.
_RESTART_OPENERS = frozenset('"\'`*’”')


def restart_key(text):
    """The opening a glued second answer would restate: the reply's first
    non-empty line, stripped, cut to RESTART_KEY_MAX chars -- or None when it
    is too short or too plain to be distinctive (a bare "4", "Yes.", a code
    fence) or not complete yet (no newline and under RESTART_KEY_MAX chars).
    Never raises."""
    try:
        if not isinstance(text, str):
            return None
        s = text[:2048].lstrip()          # the head only: O(1) on a long stream
        nl = s.find("\n")
        if nl < 0 and len(s) < RESTART_KEY_MAX:
            return None
        line = s if nl < 0 else s[:nl]
        key = line.strip()[:RESTART_KEY_MAX]
        if len(key) < _RESTART_KEY_MIN or key.startswith("```"):
            return None
        if len(_RESTART_WORD_RE.findall(key)) < _RESTART_KEY_WORDS:
            return None
        return key
    except Exception:                                            # noqa: BLE001
        return None


def restart_boundary(before, cur):
    """The character test of restart_glued_at: `before` is the text right
    before the restatement (its last two characters are enough), `cur` the
    restatement's first character. Never raises."""
    try:
        if not before or not cur:
            return False
        prev = before[-1]
        if prev.isspace():
            return False
        if prev.isalnum():
            return cur.isupper()              # else one word running on
        if prev not in _RESTART_PREV:
            return False
        if prev in _RESTART_OPENERS and (len(before) < 2 or before[-2].isspace()):
            return False                      # an opening quote/emphasis, not an end
        return True
    except Exception:                                            # noqa: BLE001
        return False


def restart_glued_at(text, q):
    """True when a restatement starting at `q` is glued onto what precedes it:
    the answer before it ENDS right there (sentence punctuation, a closing
    bracket/quote/fence, or a word run straight into a capital), not inside a
    code fence, and not an opening quote / a word running on. Never raises."""
    try:
        if q <= 0 or q >= len(text):
            return False
        if not restart_boundary(text[max(0, q - 2):q], text[q]):
            return False
        return text.count("```", 0, q) % 2 == 0
    except Exception:                                            # noqa: BLE001
        return False


def glued_restart(text, key=None, start=0, first_end=None):
    """Offset in `text` where a glued second answer starts (see above), or
    None. `key` defaults to restart_key(text); `first_end` (where the opening
    itself ends) is found when not given. Only occurrences at or after
    `start` are looked at, so a stream re-checks just its new text. Never
    raises."""
    try:
        if not isinstance(text, str):
            return None
        key = key or restart_key(text)
        if not key:
            return None
        if first_end is None:
            first = text.find(key)
            if first < 0:
                return None
            first_end = first + len(key)
        pos = max(first_end, start)
        while True:
            q = text.find(key, pos)
            if q < 0:
                return None
            if restart_glued_at(text, q):
                return q
            pos = q + 1
    except Exception:                                            # noqa: BLE001
        return None


# --------------------------------------------------------------------------- #
# Early release for the stream hold-back gate
# --------------------------------------------------------------------------- #
# The gate holds a stream's first visible text until it can judge it. Every
# junk sample it exists for is SHORT or GLUED: "3324TouchableOpacity_FP$.
# Actually, the answer is" (a brevity prompt), "319231923192" (a glued loop),
# a leaked <think>/<|im_end|>. Once the held text is ordinary prose or code,
# waiting for 400 chars / 2.5 s only costs first-token latency, so the gate
# releases as soon as reads_as_answer() says so (inspect() still judges it).
EARLY_MIN_CHARS = 80
_EARLY_MIN_WORDS = 10
_EARLY_MIN_DISTINCT = 0.6       # distinct words / words
_EARLY_MAX_WORD = 40            # a longer "word" is a glued run or a blob
_EARLY_MIN_WORDCHAR = 0.55      # letters+digits share of non-space chars
_EARLY_MARKER_RE = re.compile(r"<\s*/?\s*(?:think|thinking|tool_call|arg_)|<\||\|>|"
                              r"\bThought:|Thinking content", re.I)


def reads_as_answer(text, *, last_prompt=None):
    """True when `text` (the start of a streamed reply, no finish yet) already
    reads as a normal answer: >= EARLY_MIN_CHARS of varied words, no glued
    run, no reasoning/template marker, and the prompt does not constrain the
    reply to a number/word/yes-no (there the whole short answer IS the
    thing judged). Code counts: it has words and punctuation too. Never
    raises (False)."""
    try:
        if not isinstance(text, str) or len(text.strip()) < EARLY_MIN_CHARS:
            return False
        if last_prompt:
            lp = _instruction(str(last_prompt)) or ""
            if len(lp) <= _BRIEF_PROMPT_MAX:
                kinds, literal = _brief_kinds(lp)
                if kinds or literal:
                    return False
        if _EARLY_MARKER_RE.search(text):
            return False
        words = text.split()
        if len(words) < _EARLY_MIN_WORDS:
            return False
        if max(len(w) for w in words) > _EARLY_MAX_WORD:
            return False
        if len(set(words)) < _EARLY_MIN_DISTINCT * len(words):
            return False
        dense = [c for c in text if not c.isspace()]
        if sum(1 for c in dense if c.isalnum()) < _EARLY_MIN_WORDCHAR * len(dense):
            return False
        return True
    except Exception:                                            # noqa: BLE001
        return False


def inspect(text, *, prompt_text=None, tools_offered=False, finish_reason=None,
            last_prompt=None, partial=False):
    """Judge one answer's text.

    Returns {"ok": bool, "reasons": [...], "salvage": str|None}. `reasons` may
    hold "truncated" even when ok is True (informational). `salvage` is the
    clean answer before the junk started, or None when the junk is not just a
    tail (nothing meaningful precedes it). `last_prompt` is the LAST user
    turn: the brevity constraint ("answer with only the number") is read from
    it alone, since an earlier turn's format request does not bind a later
    "now explain why"; it defaults to `prompt_text`. Never raises: any
    internal error reports ok=True -- the gate must never be the thing that
    loses an answer. `partial`: `text` is a stream still in progress (no
    finish yet), so loops reaching its current end need the mid-text copy
    count and an inline code span still open at the end is masked."""
    result = {"ok": True, "reasons": [], "salvage": None}
    try:
        if not isinstance(text, str) or not text.strip():
            return result
        if prompt_text is not None and not isinstance(prompt_text, str):
            prompt_text = str(prompt_text)
        if last_prompt is None:
            last_prompt = prompt_text
        elif not isinstance(last_prompt, str):
            last_prompt = str(last_prompt)
        if finish_reason == "length":
            result["reasons"].append("truncated")
        # Long answers: judge the tail only. A loop or leak that ran to the cap
        # is AT the tail, and indices below are shifted back onto `text`.
        offset = max(0, len(text) - _MAX_SCAN)
        body = _clip(text)
        masked = _mask_code(body, partial)
        loop_masked = _mask_fences_distinct(body)
        loop_fin = PARTIAL if partial and not finish_reason else finish_reason
        cuts = []
        checks = (
            ("runaway_script", lambda: _script_switch(body, masked, prompt_text,
                                                      finish_reason, at_start=offset == 0)),
            ("repetition", lambda: _line_loop(loop_masked, prompt_text, loop_fin)),
            ("repetition", lambda: _tail_loop(loop_masked, prompt_text, loop_fin)),
            ("repetition", lambda: _glued_loop(loop_masked, prompt_text, loop_fin)),
            ("separator_run", lambda: _separator_run(masked, finish_reason)),
            ("tool_markup", lambda: _markup_leak(masked, prompt_text, tools_offered)),
            ("reasoning_leak", lambda: _reasoning_leak(masked, prompt_text)),
            ("template_junk", lambda: (None if offset else
                                       _special_token_junk(body, prompt_text))),
            ("metadata_leak", lambda: _meta_leak(masked, body, prompt_text,
                                                 at_start=offset == 0)),
        )
        for reason, fn in checks:
            cut = fn()
            if cut is None:
                continue
            if reason not in result["reasons"]:
                result["reasons"].append(reason)
            cuts.append(offset + cut)
        # judged on the reply's HEAD (a leading answer), so never offset
        cut = _constrained_extra(text, last_prompt, tools_offered)
        if cut is not None:
            result["reasons"].append("extra_text")
            cuts.append(cut)
        cut = _glued_foreign(text, last_prompt, prompt_text)
        if cut is not None:
            result["reasons"].append("glued_junk")
            cuts.append(cut)
        cut = glued_restart(text)
        if cut is not None:
            result["reasons"].append("restarted")
            cuts.append(cut)
        # Informational like "truncated": flagged, never cut (see
        # echoed_decimal). Only on a finished reply -- a stream in progress
        # may still be writing the real answer.
        if not partial and echoed_decimal(text, last_prompt, tools_offered):
            result["reasons"].append("echoed_decimal")
        if not cuts:
            return result
        result["ok"] = False
        clean = text[:min(cuts)].rstrip()
        if re.search(r"\w", clean) and not _splits_a_number(text, clean):
            result["salvage"] = clean
        return result
    except Exception:                                            # noqa: BLE001
        return {"ok": True, "reasons": [], "salvage": None}


# --------------------------------------------------------------------------- #
# Rolling tail check for a stream still in progress
# --------------------------------------------------------------------------- #
# 8 copies (the mid-text count) of a 160-char unit must fit.
TAIL_WINDOW = 1300


def inspect_tail(text, *, window=TAIL_WINDOW, prompt_text=None, tools_offered=False,
                 state=None, last_prompt=None):
    """Offset in `text` where junk starts, judged on its last `window` chars
    only, or None. For a STREAM already released to the client: run on every
    visible delta, so it must stay O(window), and it never judges the head
    (inspect() did that once, on the hold-back window).

    Only the tail-shaped failures: a loop running to the current end, a
    separator run, a script switch, leaked tool/reasoning/metadata markup.
    The head-shaped ones (the brevity trim, a junk run glued onto the bare
    number) run only while the WHOLE text still fits the window and
    `last_prompt` asks for a bare value: a short answer released by the hold
    window's clock ("4349" after 2.5 s of a slow model) may still grow the
    junk that inspect() never saw. No finish_reason: the stream has not
    finished, so its current end is not the answer's end and a loop reaching
    it needs the MID-text copy count (a line printed five times mid-answer is
    content until it keeps
    going). Fence state comes from the FULL text, so a window opening inside
    a code block still has that code masked. `state` (a dict the caller keeps
    per stream) caches the foreign-script scan of the text before the window,
    so repeated calls on a growing text stay O(new text). Never raises
    (None)."""
    try:
        if not isinstance(text, str) or not text.strip():
            return None
        if prompt_text is not None and not isinstance(prompt_text, str):
            prompt_text = str(prompt_text)
        start = max(0, len(text) - int(window))
        if start:
            # Open the window on a line start: a window beginning mid-"```"
            # would read the fence as prose and its code as a loop.
            line = text.rfind("\n", 0, start) + 1
            if start - line <= window:
                start = line
        pad = "```\n" if text.count("```", 0, start) % 2 else ""
        body = pad + text[start:]
        masked = _mask_code(body, True)
        loop_masked = _mask_fences_distinct(body)
        # A reply ALREADY in a foreign script is not switching now; whole-reply
        # script judgement was inspect()'s job on the head.
        if state is None:
            state = {}
        pos = state.get("fpos", 0)
        if pos > start:
            pos, state["foreign"] = 0, False
        if not state.get("foreign") and pos < start:
            state["foreign"] = _ANY_FOREIGN_RE.search(text, pos, start) is not None
        state["fpos"] = start
        script = None
        if not (start and state.get("foreign")):
            script = _script_switch(body, masked, prompt_text, None, at_start=start == 0)
        # A stray </think> only counts closing a SHORT head (inspect's rule); a
        # window's own head is not the reply's, so mid-stream it never counts.
        lead = _THINK_CLOSE_RE.sub(lambda m: " " * len(m.group(0)), masked) \
            if start else masked
        found = [c for c in (
            script,
            _line_loop(loop_masked, prompt_text, PARTIAL),
            _tail_loop(loop_masked, prompt_text, PARTIAL),
            _glued_loop(loop_masked, prompt_text, PARTIAL),
            _separator_run(masked, None),
            _markup_leak(masked, prompt_text, tools_offered),
            _reasoning_leak(lead, prompt_text),
            _meta_leak(masked, body, prompt_text, at_start=start == 0),
        ) if c is not None]
        if start == 0 and last_prompt:
            # the whole reply is in view (pad is "" at start 0): judge its head
            lp = last_prompt if isinstance(last_prompt, str) else str(last_prompt)
            found.extend(c for c in (_constrained_extra(text, lp, tools_offered),
                                     _glued_foreign(text, lp, prompt_text))
                         if c is not None)
        # A glued second answer (restart_key reads only the reply's head).
        r = glued_restart(text, start=start)
        if r is not None:
            found.append(r - start + len(pad))
        if not found:
            return None
        return max(0, start + min(found) - len(pad))
    except Exception:                                            # noqa: BLE001
        return None
